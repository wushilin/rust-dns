#!/usr/bin/env python3
"""Write a Homebrew formula for a rust-dns release (O19).

Usage: homebrew-formula.py <version> <tag> <sha256-of-source-tarball> [repo] > rust-dns.rb

The formula builds from the tagged source with cargo (macOS and Linux);
the release workflow attaches it to the GitHub release. Homebrew installs
formulae only from a tap, so put it in one (a local tap is enough):

    brew tap-new --no-git $USER/local
    cp rust-dns.rb "$(brew --repository)/Library/Taps/$USER/homebrew-local/Formula/"
    HOMEBREW_GITHUB_API_TOKEN=$(gh auth token) brew install $USER/local/rust-dns

While the repository is private the source download needs a token with
read access: the formula sends `HOMEBREW_GITHUB_API_TOKEN`.
"""
import re
import sys

TEMPLATE = '''# Generated by scripts/homebrew-formula.py for {tag}; do not edit.
class RustDns < Formula
  desc "SQLite-backed authoritative DNS server with a realtime web console"
  homepage "https://github.com/{repo}"
  # The repository is private: the archive is fetched with a token
  # (export HOMEBREW_GITHUB_API_TOKEN, e.g. from `gh auth token`).
  url "https://github.com/{repo}/archive/refs/tags/{tag}.tar.gz",
      headers: ["Authorization: token #{{ENV.fetch("HOMEBREW_GITHUB_API_TOKEN", "")}}"]
  version "{version}"
  sha256 "{sha256}"
  license "Apache-2.0"

  depends_on "rust" => :build

  def install
    system "cargo", "install", *std_cargo_args
    (etc/"rust-dns").mkpath
    (var/"rust-dns").mkpath
    pkgshare.install "examples"
  end

  def caveats
    <<~EOS
      Create a configuration (prints a random root password once):
        rust-dns --init-config #{{etc}}/rust-dns/rust-dns.toml
      Port 53 needs root; for a user service pick another [server] port.
      Example configurations: #{{opt_pkgshare}}/examples
    EOS
  end

  service do
    run [opt_bin/"rust-dns", "--config", etc/"rust-dns/rust-dns.toml"]
    working_dir var/"rust-dns"
    keep_alive true
    log_path var/"log/rust-dns.log"
    error_log_path var/"log/rust-dns.log"
  end

  test do
    assert_match "rust-dns #{{version}}", shell_output("#{{bin}}/rust-dns --version")
    (testpath/"t.toml").write <<~EOS
      [root]
      username = "root"
      password = "brew-test-password-1"
    EOS
    system bin/"rust-dns", "--check", "--config", testpath/"t.toml"
  end
end
'''


def main():
    if len(sys.argv) not in (4, 5):
        raise SystemExit(__doc__)
    version, tag, sha256 = sys.argv[1:4]
    repo = sys.argv[4] if len(sys.argv) == 5 else "wushilin/rust-dns"
    if not re.fullmatch(r"[0-9a-f]{64}", sha256):
        raise SystemExit("sha256 must be 64 lower-case hex digits")
    if not re.fullmatch(r"[0-9][0-9A-Za-z.+-]*", version.lstrip("v")):
        raise SystemExit(f"bad version {version}")
    sys.stdout.write(TEMPLATE.format(version=version.lstrip("v"), tag=tag, sha256=sha256, repo=repo))


if __name__ == "__main__":
    main()
