//! TSIG keys (RFC 8945) for zone transfers and NOTIFY. Writes go through
//! [`AuditTx`], so every create, scope change, delete and reveal has an audit
//! row committed with it. Audit details carry the key name, algorithm and
//! zones, never the secret.

use super::accounts::AuditTx;
use crate::dns::tsig::Algorithm;
use crate::model::{normalize_domain, normalize_zone_name, now_rfc3339, Invalid};
use crate::storage::StoredTsigKey;
use anyhow::Result;
use rand::RngCore;

/// Longest secret we accept on import (bytes). HMAC hashes longer keys first.
pub const MAX_SECRET_BYTES: usize = 512;
/// Shortest secret we accept on import (bytes, 128 bits).
pub const MIN_SECRET_BYTES: usize = 16;
/// Zones one key may be scoped to.
pub const MAX_ZONES: usize = 256;

/// `Hn-Secondary` / `hn-secondary.` -> `hn-secondary.`. Key names are DNS
/// names (they travel as the TSIG owner name); underscores are allowed.
pub fn normalize_key_name(raw: &str) -> Result<String, Invalid> {
    let t = raw.trim();
    if t.is_empty() || t == "." {
        return Err(Invalid("key name is required, e.g. hn-secondary.".into()));
    }
    if !t.is_ascii() {
        return Err(Invalid(
            "key names must be ASCII (letters, digits, '-', '_' and dots)".into(),
        ));
    }
    let n = normalize_domain(t, true)
        .map_err(|e| Invalid(format!("key name '{t}' is invalid: {}", e.0)))?;
    Ok(format!("{n}."))
}

/// Parse an imported base64 secret. The error never echoes the input.
pub fn parse_secret(b64: &str) -> Result<Vec<u8>, Invalid> {
    let t: String = b64.chars().filter(|c| !c.is_whitespace()).collect();
    let bytes = data_encoding::BASE64
        .decode(t.as_bytes())
        .or_else(|_| data_encoding::BASE64_NOPAD.decode(t.as_bytes()))
        .map_err(|_| Invalid("secret is not valid base64".into()))?;
    if bytes.len() < MIN_SECRET_BYTES {
        return Err(Invalid(format!(
            "secret is too short ({} bytes); use at least {MIN_SECRET_BYTES} bytes (a key generated by tsig-keygen or your secondary provider)",
            bytes.len()
        )));
    }
    if bytes.len() > MAX_SECRET_BYTES {
        return Err(Invalid(format!(
            "secret is too long; at most {MAX_SECRET_BYTES} bytes"
        )));
    }
    Ok(bytes)
}

/// A random secret as long as the hash output (RFC 8945 §6 recommends at
/// least that much).
pub fn generate_secret(alg: Algorithm) -> Vec<u8> {
    let mut buf = vec![0u8; alg.mac_len()];
    rand::rng().fill_bytes(&mut buf);
    buf
}

pub fn encode_secret(secret: &[u8]) -> String {
    data_encoding::BASE64.encode(secret)
}

/// Normalise a zone scope: valid zone names, sorted, de-duplicated. Empty
/// means the key may transfer every zone.
pub fn normalize_zones(raw: &[String]) -> Result<Vec<String>, Invalid> {
    let mut out: Vec<String> = Vec::new();
    for z in raw.iter().map(|z| z.trim()).filter(|z| !z.is_empty()) {
        let n = normalize_zone_name(z).map_err(|e| Invalid(format!("zone '{z}': {}", e.0)))?;
        if !out.contains(&n) {
            out.push(n);
        }
    }
    if out.len() > MAX_ZONES {
        return Err(Invalid(format!("at most {MAX_ZONES} zones per key")));
    }
    out.sort();
    Ok(out)
}

/// A key to create (already validated).
pub struct NewTsigKey {
    pub name: String,
    pub algorithm: Algorithm,
    pub secret: Vec<u8>,
    pub zones: Vec<String>,
    /// True when the secret was supplied by the administrator.
    pub imported: bool,
}

fn detail(k: &StoredTsigKey) -> serde_json::Value {
    serde_json::json!({ "name": k.name, "algorithm": k.algorithm, "zones": k.zones })
}

impl AuditTx<'_> {
    /// Create a key. `Ok(None)` when a key with this name already exists.
    pub fn create_tsig_key(
        &mut self,
        actor: &str,
        k: &NewTsigKey,
    ) -> Result<Option<StoredTsigKey>> {
        if self.tsig_key(&k.name)?.is_some() {
            return Ok(None);
        }
        let now = now_rfc3339();
        self.record(crate::mutation::SecretChange::TsigKeySet {
            key: crate::replication::types::ReplTsigKey {
                name: k.name.clone(),
                algorithm: k.algorithm.name().to_string(),
                secret: data_encoding::BASE64.encode(&k.secret),
                zones: k.zones.clone(),
                created_by: actor.to_string(),
                created_at: now.clone(),
                updated_at: now,
            },
        })?;
        let key = self.tsig_key(&k.name)?.expect("just inserted");
        let mut d = detail(&key);
        d["source"] = serde_json::json!(if k.imported { "imported" } else { "generated" });
        self.push("tsig.create", None, &key.name, d);
        Ok(Some(key))
    }

    /// Replace the zone scope of a key.
    pub fn update_tsig_key_zones(
        &mut self,
        before: &StoredTsigKey,
        zones: &[String],
    ) -> Result<StoredTsigKey> {
        if before.zones != zones {
            let mut row = crate::replication::data::tsig_row(before.clone());
            row.zones = zones.to_vec();
            row.updated_at = now_rfc3339();
            self.record(crate::mutation::SecretChange::TsigKeySet { key: row })?;
        }
        let after = self.tsig_key(&before.name)?.expect("exists");
        if before.zones != after.zones {
            self.push(
                "tsig.update",
                None,
                &after.name,
                serde_json::json!({ "zones": [before.zones, after.zones] }),
            );
        }
        Ok(after)
    }

    pub fn delete_tsig_key(&mut self, k: &StoredTsigKey) -> Result<bool> {
        let n = usize::from(self.tsig_key(&k.name)?.is_some());
        if n > 0 {
            self.record(crate::mutation::SecretChange::TsigKeyDeleted {
                name: k.name.clone(),
            })?;
        }
        if n > 0 {
            self.push("tsig.delete", None, &k.name, detail(k));
        }
        Ok(n > 0)
    }

    /// Record that an administrator displayed the secret. Nothing is written
    /// but the audit row.
    pub fn reveal_tsig_key(&mut self, k: &StoredTsigKey) -> Result<()> {
        self.push(
            "tsig.reveal",
            None,
            &k.name,
            serde_json::json!({ "name": k.name, "algorithm": k.algorithm }),
        );
        Ok(())
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::model::Actor;
    use crate::mutation::accounts::Accounts;
    use crate::storage::Storage;
    use std::sync::Arc;

    #[test]
    fn names_secrets_zones() {
        assert_eq!(normalize_key_name("HN-Secondary").unwrap(), "hn-secondary.");
        assert_eq!(normalize_key_name("a_b.example.").unwrap(), "a_b.example.");
        assert!(normalize_key_name("").is_err());
        assert!(normalize_key_name(".").is_err());
        assert!(normalize_key_name("bad..name").is_err());
        assert!(normalize_key_name("bad name").is_err());

        let s = generate_secret(Algorithm::HmacSha384);
        assert_eq!(s.len(), 48);
        assert_eq!(parse_secret(&encode_secret(&s)).unwrap(), s);
        let e = parse_secret("c2VjcmV0").unwrap_err().0; // "secret": 6 bytes
        assert!(e.contains("too short"), "{e}");
        assert!(!e.contains("c2VjcmV0"));
        let e = parse_secret("not base64 !!").unwrap_err().0;
        assert_eq!(e, "secret is not valid base64");
        // Whitespace (line-wrapped pastes) is ignored; missing padding is accepted.
        let s16 = [7u8; 16];
        let b = encode_secret(&s16);
        assert_eq!(
            parse_secret(&format!(" {}\n{} ", &b[..8], &b[8..])).unwrap(),
            s16
        );
        assert_eq!(parse_secret(b.trim_end_matches('=')).unwrap(), s16);

        assert_eq!(
            normalize_zones(&[
                "B.example.".into(),
                "a.example".into(),
                "b.example".into(),
                " ".into()
            ])
            .unwrap(),
            vec!["a.example".to_string(), "b.example".to_string()]
        );
        assert!(normalize_zones(&["bad..zone".into()]).is_err());
    }

    #[test]
    fn lifecycle_is_audited_without_secrets() {
        let s = Arc::new(Storage::open_memory().unwrap());
        let a = Accounts::new(s.clone());
        let actor = Actor {
            name: "root".into(),
            ip: "127.0.0.1".into(),
        };
        let secret = generate_secret(Algorithm::HmacSha256);
        let b64 = encode_secret(&secret);
        let new = NewTsigKey {
            name: "hn-secondary.".into(),
            algorithm: Algorithm::HmacSha256,
            secret: secret.clone(),
            zones: vec!["example.com".into()],
            imported: false,
        };
        let k = a
            .run(&actor, "create_tsig_key", |t| {
                t.create_tsig_key("root", &new)
            })
            .unwrap()
            .unwrap();
        assert_eq!(k.secret, secret);
        assert_eq!(k.created_by, "root");
        assert!(a
            .run(&actor, "create_tsig_key", |t| t
                .create_tsig_key("root", &new))
            .unwrap()
            .is_none());
        let k = a
            .run(&actor, "update_tsig_key", |t| {
                t.update_tsig_key_zones(&k, &[])
            })
            .unwrap();
        assert!(k.zones.is_empty());
        a.run(&actor, "reveal_tsig_key", |t| t.reveal_tsig_key(&k))
            .unwrap();
        assert!(a
            .run(&actor, "delete_tsig_key", |t| t.delete_tsig_key(&k))
            .unwrap());
        assert!(s.get_tsig_key("hn-secondary.").unwrap().is_none());

        let audit = s.audit_after(0, 100).unwrap();
        let actions: Vec<&str> = audit.iter().map(|r| r.action.as_str()).collect();
        assert_eq!(
            actions,
            ["tsig.create", "tsig.update", "tsig.reveal", "tsig.delete"]
        );
        for r in &audit {
            let d = r.detail.to_string();
            assert!(!d.contains(&b64), "secret in audit detail: {d}");
            assert!(!d.contains(&hex::encode(&secret)));
            assert_eq!(r.target, "hn-secondary.");
        }
        assert_eq!(audit[0].detail["source"], "generated");
    }
}
